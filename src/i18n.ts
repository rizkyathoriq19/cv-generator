export const STRINGS: Record<Lang, Strings> = { english: EN, indonesian: ID };

/** Interface language is an application preference, never part of a CV. */
const LANG_KEY = 'cvgen.interfaceLanguage';

export const storedLang = (): Lang => (localStorage.getItem(LANG_KEY) === 'indonesian' ? 'indonesian' : 'english');

export const saveLang = (lang: Lang) => localStorage.setItem(LANG_KEY, lang);

/** Interface strings for the selected language; editor sections read this. */
export const LangContext = createContext<{ lang: Lang; t: Strings }>({
  lang: 'english',
  t: STRINGS.english,
});

export const useT = () => useContext(LangContext);
